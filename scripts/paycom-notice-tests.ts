function message(
  subject: string,
  text: string,
  from = "systemmessage@paycomonline.com",
  isInbound = true
): FrontMessage {
  return {
    id: `msg_test_${subject.length}_${text.length}`,
    is_inbound: isInbound,
    subject,
    text,
    recipients: [
      { handle: from, role: "from" },
      { handle: "aschaedig@skyshare.com", role: "to" }
    ]
  } as FrontMessage;
}

/** What a Front rule routing a Paycom notice into a shared inbox looks like when
    it forwards rather than moves: the original headers survive in the body. */
function forwarded(originalSubject: string, originalBody: string): string {
  return (
    "---------- Forwarded message ---------\n" +
    "From: Paycom <systemmessage@paycomonline.com>\n" +
    "Date: Sat, Aug 15, 2026 at 2:00 PM\n" +
    `Subject: ${originalSubject}\n` +
    "To: <aschaedig@skyshare.com>\n\n" +
    originalBody
  );
}

