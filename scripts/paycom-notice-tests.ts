/**
 * "Recognised" outcomes — the notice was identified and the app went on to try to
 * place it. Whether it then ticked, found the step already done, or failed to
 * match a person depends on live roster data.
 *
 * ASSERTING ON THIS RATHER THAN ON "ticked" IS DELIBERATE. A test that demanded
 * would-tick would go red the day Dayten Schureman is ticked for real (he now is)
 * or leaves the roster — failures that say nothing about the parser. What this
 * file exists to protect is the CLASSIFICATION: that the right notice is
 * recognised and the three lookalikes are refused.
 */
const RECOGNISED = new Set(["would-tick", "ticked", "already-done", "no-match", "ambiguous-match", "no-such-task"]);

