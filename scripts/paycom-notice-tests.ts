/**
 * Guard for the Paycom notice classifier.
 *
 *   npx tsx scripts/paycom-notice-tests.ts
 *
 * READ ONLY — every case runs with dryRun: true, so nothing is ticked, tagged or
 * written. It does read the live new-hire roster, because matching against real
 * people is part of what is being tested.
 *
 * WHY THIS EXISTS, AND WHY IT IS NOT OPTIONAL
 *
 * Paycom sends FOUR offer notices about the same person, from the same address,
 * all of which contain "offer for NAME (id) to fill Requisition N":
 *
 *   "Pending Offer Approval"                    there IS a pending offer
 *   "ACTION REQUIRED: Pending Offer Approved"   ...has been APPROVED (internally)
 *   "Pending Offer Expires Soon"                ...expires soon
 *   "Offer Accepted"                            ...has been ACCEPTED  <- the only one
 *
 * Only the last means the candidate said yes. "Approved" is OUR approver signing
 * off, which happens before the offer even reaches the candidate. Dayten
 * Schureman's real sequence was Approval Aug 10, Approved Aug 10/13/14, Accepted
 * Aug 15 — so a pattern loosened to /offer.*approved/ or a bare /offer/ would
 * tick "Candidate signed offer letter" five days early, on a person who could
 * still decline. Nothing would throw. The checklist would simply be wrong, and a
 * recruiter would believe a signed offer was on file.
 *
 * Every body below is VERBATIM from Paycom's mail. The refusals matter more than
 * the acceptances: if you are here because you loosened a regex and this went
 * red, that is the test doing its job.
 *
 * The repo has no test runner, so this follows the pattern of
 * scripts/pilot-app-dry-run.ts — a script you run, exiting non-zero on failure so
 * it can be used as a gate.
 *
 * ENV: FRONT_API_TOKEN is not needed (nothing here talks to Front), but
 * DATABASE_URL is, and it lives in .env while .env.local holds everything else.
 * Both are loaded below, .env.local first so it wins.
 */
